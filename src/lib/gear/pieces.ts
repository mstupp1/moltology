/** Permanent id for a piece added after the originals. */
const laterId = (n: number) => `a4000000-0000-4000-8000-${String(n).padStart(12, '0')}`

type CollectionFields = Omit<GearPiece, 'id' | 'primaryStat' | 'affixes' | 'ladder' | 'collection' | 'sortOrder'>

/** A collection piece: permanent id from `n`, stats from rarity plus the set's lean, no recoloured ladder. */
function collection(id: string, lean: EquipmentAffix['stat'], pieces: CollectionFields[]): GearPiece[] {
  return pieces.map((p) => ({ ...p, id: laterId(p.n), ...tierStats(p.slot, p.rarity, lean), ladder: false, collection: id, sortOrder: p.n }))
}

